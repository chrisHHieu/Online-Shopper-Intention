"""Optuna tuning end to end on the fixture, and the config it writes back."""

from __future__ import annotations

import pytest
import yaml

from shopper_intent.config import load_config
from shopper_intent.tuning.search import tune

pytestmark = pytest.mark.modern


def _fast_config(config, tmp_path):
    tuning = config.tuning.model_copy(
        update={"trials": 1, "storage": str(tmp_path / "optuna.db"), "timeout_seconds": 600}
    )
    return config.model_copy(update={"tuning": tuning})


def test_one_trial_writes_a_loadable_config(fixture_config, tmp_path) -> None:
    pytest.importorskip("optuna")
    config = _fast_config(fixture_config, tmp_path)
    out = tmp_path / "tuned.yaml"
    results = tune(config, models=["logistic"], trials=1, timeout=600, out=out)

    payload = results["models"]["logistic"]
    assert payload["completed"] == 1
    assert "C" in payload["best_params"]
    assert out.is_file()

    loaded = load_config(out)
    assert loaded.model.logistic.C == pytest.approx(payload["best_params"]["C"])
    assert loaded.model.candidates == fixture_config.model.candidates
    assert loaded.features.categorical == fixture_config.features.categorical


def test_tuned_config_records_the_run(fixture_config, tmp_path) -> None:
    pytest.importorskip("optuna")
    config = _fast_config(fixture_config, tmp_path)
    out = tmp_path / "tuned.yaml"
    results = tune(config, models=["logistic"], trials=1, timeout=600, out=out)
    text = out.read_text(encoding="utf-8")
    assert "# Generated by `tune`" in text
    assert results["finished_at"] in text
    data = yaml.safe_load(text)
    assert data["project"]["version"] == fixture_config.project.version


def test_the_threshold_is_reported_for_the_best_trial(fixture_config, tmp_path) -> None:
    pytest.importorskip("optuna")
    config = _fast_config(fixture_config, tmp_path)
    results = tune(config, models=["logistic"], trials=1, timeout=600, out=tmp_path / "t.yaml")
    payload = results["models"]["logistic"]
    assert 0.0 < payload["best_threshold"] < 1.0
    assert payload["best_pr_auc_oof"] is not None
